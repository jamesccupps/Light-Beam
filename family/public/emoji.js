const RECENT_KEY = 'family.emoji.recent';
function recent() {
  try { return JSON.parse(localStorage.getItem(RECENT_KEY) || '[]').slice(0, 24); } catch { return []; }
}
export function noteUsed(e) {
  try { localStorage.setItem(RECENT_KEY, JSON.stringify([e, ...recent().filter(x => x !== e)].slice(0, 24))); } catch {}
}

// Opens the picker next to `anchor` (a sheet on a phone); onPick(emoji).
export function pickEmoji(anchor, onPick) {
  document.querySelector('.emoji-pop')?.dispatchEvent(new Event('close'));
  const phone = isPhone() || isTouch();
  const tabs = [['🕘', 'Recent', recent().join(' ') || QUICK.join(' ')], ...CATEGORIES];
  const grid = h('div', { class: 'emoji-grid', role: 'listbox', 'aria-label': 'Emoji' });
  const tabBar = h('div', { class: 'emoji-tabs', role: 'tablist' });
  let scrim = null;
  const pop = h('div', { class: `emoji-pop ${phone ? 'sheet' : 'menu'}`, role: 'dialog', 'aria-label': 'Choose an emoji' }, phone ? h('div', { class: 'grab' }) : null, tabBar, grid);
  const close = () => {
    pop.remove();
    scrim?.remove();
    document.removeEventListener('pointerdown', outside, true);
    document.removeEventListener('keydown', onKey, true);
  };
  pop.addEventListener('close', close);
  const show = i => {
    fill(grid, ...tabs[i][2].split(' ').filter(Boolean).map(e => h('button', { type: 'button', role: 'option', 'aria-label': e, onclick: () => { noteUsed(e); close(); onPick(e); } }, e)));
    [...tabBar.children].forEach((b, j) => b.classList.toggle('on', i === j));
    grid.scrollTop = 0;
  };
  tabs.forEach(([glyph, label], i) => tabBar.append(h('button', { type: 'button', role: 'tab', title: label, 'aria-label': label, onclick: () => show(i) }, glyph)));
  show(0);
  if (phone) {
    scrim = h('div', { class: 'scrim', onclick: close });
    document.body.append(scrim);
  }
  document.body.append(pop);
  if (!phone) {
    const r = anchor.getBoundingClientRect();
    const w = pop.offsetWidth;
    const hgt = pop.offsetHeight;
    const left = Math.max(8, Math.min(r.right - w, window.innerWidth - w - 8));
    const top = r.top - hgt - 6 > 8 ? r.top - hgt - 6 : Math.min(r.bottom + 6, window.innerHeight - hgt - 8);
    Object.assign(pop.style, { left: `${left}px`, top: `${top}px` });
  }
  const outside = e => { if (!pop.contains(e.target) && e.target !== anchor && !anchor.contains(e.target)) close(); };
  const onKey = e => { if (e.key === 'Escape') { e.stopPropagation(); close(); } };
  setTimeout(() => document.addEventListener('pointerdown', outside, true));
  document.addEventListener('keydown', onKey, true);
  return close;
}
